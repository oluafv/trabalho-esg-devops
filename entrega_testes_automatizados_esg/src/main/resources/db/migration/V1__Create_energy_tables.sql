-- Tabela de Equipamentos
CREATE TABLE tb_equipamentos (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL,
    setor VARCHAR2(50) NOT NULL,
    limite_consumo_kwh NUMBER(10, 2) NOT NULL,
    status VARCHAR2(20) DEFAULT 'ATIVO' NOT NULL
);

-- Tabela de Medições de Energia (Integrado com IoT)
CREATE TABLE tb_medicoes (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipamento_id NUMBER NOT NULL,
    consumo_kwh NUMBER(10, 2) NOT NULL,
    data_medicao TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_equipamento FOREIGN KEY (equipamento_id) REFERENCES tb_equipamentos(id)
);